// The design-system repo, as files. ONE builder for every sink: the Figma
// plugin's "Save to GitHub" (browser-direct to api.github.com, no Escala
// server), and later the web push, the wizard zip and the CLI.
//
// Pure: takes a TokenJSON, never the store, React or the Blob — the plugin
// bundles this file (escala-figma-plugin/build.mjs). Additive to what the web
// push already writes: `tokens.json`, `variables.css`, `README.md` and the
// agent package stay at the same paths, so existing repos keep working.

import { repoSkillFiles } from '../agentBundle/repoSkills'
import { skillName } from '../agentBundle/names'
import type { TokenJSON } from '../agentBundle/types'
import { buildComponentContracts, contractKeys, CONTRACTS_DIR } from './componentContracts'
import type { RepoBuild, RepoBuildOptions, RepoFile } from './types'
import { leadBrandCss, leadBrandJson, leadBrandKey } from './leadBrandJson'
import { componentDocsSection } from './componentDocs'
import { brandSlug } from '../cssCut'

export const README_MARKER = '<!-- escala:readme -->'
export const SCHEMA_URL = 'https://www.escalatokens.com/docs/agent-native/tokens.schema.json'

/**
 * Whether a push may write `README.md`. Never over a README someone wrote: only
 * when there is none, when Escala wrote it, or when it is GitHub's auto-init
 * stub (`# repo-name` plus at most a one-line description).
 */
/** The line the web's README carried before it was stamped with
 *  README_MARKER (pushes up to 2026-10-31). Recognised so those READMEs — Escala's
 *  own — can still be replaced; a person's README never carries it near the top. */
const LEGACY_WEB_README = /^> Generated by \[Escala Tokens\]\(https:\/\/www\.escalatokens\.com\)\s*$/m

export function shouldWriteReadme(existing: string | null | undefined): boolean {
  if (existing == null) return true
  if (existing.includes(README_MARKER)) return true
  if (LEGACY_WEB_README.test(existing.slice(0, 400)) && existing.trimStart().startsWith('# ')) return true
  const lines = existing.split('\n').map((l) => l.trim()).filter(Boolean)
  return lines.length <= 2 && (lines[0] ?? '').startsWith('# ')
}

function projectOf(json: TokenJSON, opts: RepoBuildOptions): string {
  return json.project?.trim() || opts.projectFallback?.trim() || 'Design system'
}

/** A real role of THIS system, for the naming examples. */
function sampleRole(json: TokenJSON): string {
  const tokens = (json.colors as { architecture?: { tokens?: Record<string, Record<string, unknown>> } } | undefined)
    ?.architecture?.tokens
  if (tokens) {
    for (const group of Object.keys(tokens)) {
      const role = Object.keys(tokens[group] ?? {})[0]
      if (role) return `${group}.${role}`
    }
  }
  return 'action.primary.default'
}

function figmaName(role: string): string {
  const [head, ...rest] = role.split('.')
  return [head.charAt(0).toUpperCase() + head.slice(1), ...rest].join('/')
}

function cssName(role: string): string {
  return `--color-${role.replace(/\./g, '-')}`
}

function buildNamingMd(json: TokenJSON, project: string): string {
  const role = sampleRole(json)
  return [
    `# Naming — ${project}`,
    '',
    'One token, three spellings. Never invent a fourth.',
    '',
    '| World | Rule | Example |',
    '|---|---|---|',
    `| JSON (\`tokens.json\`) | dots | \`${role}\` |`,
    `| CSS (\`variables.css\`) | hyphens inside \`var()\` | \`var(${cssName(role)})\` |`,
    `| Figma variable | slashes | \`${figmaName(role)}\` |`,
    '',
    '- Use semantic roles (`action.*`, `surface.*`, `content.*`, `border.*`, `status.*`) in product code. Primitives (`accent-9`) are the ramp behind them.',
    '- Never hard-code a hex or a px value that a token already covers.',
    `- Payload shape: [tokens.schema.json](${SCHEMA_URL}).`,
    '',
  ].join('\n')
}

function buildContractsReadme(project: string, count: number): string {
  return [
    `# Contracts — ${project}`,
    '',
    'What code, Figma and agents must agree on. Generated by Escala on every save; edit the system in Escala, not here.',
    '',
    '| File | What it says |',
    '|---|---|',
    `| [components.json](components.json) | The whole catalogue (${count} components): \`selected\` = chosen in this system, \`inFigma\` = built in the Figma file |`,
    '| `components/<Component>.json` | Variant axes, props, accessibility, and which token paints each part (`recipe`) |',
    '| [naming.md](naming.md) | How one token is spelled in JSON, CSS and Figma |',
    `| [tokens.schema.json](${SCHEMA_URL}) | The shape of \`tokens.json\` |`,
    '',
  ].join('\n')
}

function buildReadme(
  json: TokenJSON,
  project: string,
  opts: RepoBuildOptions,
  skillDirs: string[],
  leadName: string | null = null,
  brands: { name: string; slug: string }[] = [],
): string {
  const role = sampleRole(json)
  const from = opts.source === 'figma-plugin' ? 'the Escala Figma plugin' : 'Escala'
  const rows: string[] = [
    '| `tokens.json` | The whole system (Escala JSON). Source for everything else |',
  ]
  if (opts.css) rows.push(`| \`variables.css\` | CSS custom properties${leadName ? ` of **${leadName}**` : ''}, both themes — import once, use \`var(--…)\` |`)
  for (const b of brands) rows.push(`| \`brands/${b.slug}/variables.css\` | The **${b.name}** brand |`)
  rows.push('| `contracts/` | Component contracts and naming rules |')
  if (opts.figma) rows.push('| `figma/manifest.json` | Which components are built in the Figma file, with node IDs |')
  rows.push(`| ${skillDirs.map((d) => `\`${d}\``).join(' · ')} | Skills for Claude Code and Cursor, so agents use these tokens instead of guessing |`)
  return [
    README_MARKER,
    `# ${project}`,
    '',
    `Design system generated with ${from} · [escalatokens.com](https://www.escalatokens.com).`,
    ...(leadName ? ['', `> Brand: **${leadName}**${brands.length > 1 ? ` (root files) · every brand under \`brands/\`` : ''}`] : []),
    '',
    '## What is here',
    '',
    '| Path | Contents |',
    '|---|---|',
    ...rows,
    '',
    '## Use it',
    '',
    '```css',
    "@import './variables.css';",
    '',
    `.button { background: var(${cssName(role)}); }`,
    '```',
    '',
    'Agents: start at the `AGENTS.md` inside the skills folder.',
    '',
    componentDocsSection(skillDirs[0] ?? '', json.atoms),
    '---',
    '',
    '## Change it',
    '',
    'Edit the system in Escala (web or Figma plugin) and save to GitHub again. Files Escala writes are overwritten on each save; this README is only rewritten while it keeps the marker on its first line.',
    '',
  ].join('\n')
}

function stringify(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`
}

export function buildRepoFiles(input: TokenJSON, opts: RepoBuildOptions = {}): RepoBuild {
  // README, skills and contracts read the root: make it the lead brand's.
  const json = leadBrandJson(input)
  const project = projectOf(json, opts)
  const skills = repoSkillFiles(json, {
    projectFallback: project,
    iconKey: opts.iconKey,
    generatedAt: opts.generatedAt,
  })
  const files: RepoFile[] = [{ path: 'tokens.json', content: stringify(json) }]
  // The brand's own variables.css when the payload carries it (the web's
  // buildCSS, identical to its CSS door); else what the caller rendered.
  const css = leadBrandCss(input) ?? opts.css
  if (css) files.push({ path: 'variables.css', content: css.endsWith('\n') ? css : `${css}\n` })
  // 2+ brands: each gets its own file, like the web push (`brands/` mirrors them).
  const brands = input.brandCss ?? []
  const taken = new Set<string>()
  const perBrand = brands.length > 1 ? brands.map((b) => ({ ...b, slug: brandSlug(b.name, taken) })) : []
  for (const b of perBrand) files.push({ path: `brands/${b.slug}/variables.css`, content: b.css.endsWith('\n') ? b.css : `${b.css}\n` })
  const lead = leadBrandKey(input)?.split('::')[0]
  const leadName = brands.find((b) => b.key === lead)?.name ?? null
  if (opts.readme !== false) files.push({ path: 'README.md', content: buildReadme(json, project, { ...opts, css }, skills.prefixes, leadName, perBrand) })

  files.push({ path: 'contracts/README.md', content: buildContractsReadme(project, contractKeys().length) })
  files.push({ path: 'contracts/naming.md', content: buildNamingMd(json, project) })
  files.push(...buildComponentContracts(json, opts.figma))
  if (opts.figma) files.push({ path: 'figma/manifest.json', content: stringify(opts.figma) })

  files.push(...skills.files)
  // Escala owns these folders outright, so a component dropped from the system
  // loses its contract. `figma/` is NOT pruned: a team may keep its own
  // Code Connect files there.
  return { files, prefixes: [...skills.prefixes, CONTRACTS_DIR, 'brands/'] }
}

/** Commit message for a save. */
export function repoCommitMessage(json: TokenJSON, opts: Pick<RepoBuildOptions, 'projectFallback' | 'source'> = {}): string {
  const project = projectOf(json, opts)
  const via = opts.source === 'figma-plugin' ? ' from Figma' : ''
  return `chore(design-system): update ${project}${via}`
}

