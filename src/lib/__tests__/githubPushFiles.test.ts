import { beforeEach, describe, expect, it } from 'vitest'
import { makeDesignDefaults, useDesignStore, type DesignSnapshot } from '../../store/useDesignStore'
import { adoptPreset } from '../adoptPreset'
import { THEME_STYLE_PRESETS } from '../themePresets'
import { captureCodeSnapshot } from '../codeScope'
import { buildCSS } from '../exporters'
import { BRANDS_DIR, buildGithubPushFiles } from '../githubPushFiles'
import { shouldWriteReadme } from '../repoExport'

// "Push to GitHub" ships the brand the person made — the same files its CSS /
// Agent doors ship — never the system's root defaults (blue accent, Inter).

const store = () => useDesignStore.getState() as unknown as DesignSnapshot
const preset = (id: string) => THEME_STYLE_PRESETS.find((p) => p.id === id)!
function adopt(id: string, appearance: 'light' | 'dark' = 'light'): string {
  const r = adoptPreset(preset(id), appearance, { track: false })
  if ('error' in r) throw new Error(r.error)
  return r.key
}
const file = (r: ReturnType<typeof buildGithubPushFiles>, path: string) => r.files.find((f) => f.path === path)?.content ?? ''
const accent9 = (css: string) => /--color-accent-9:\s*([^;]+);/.exec(css)?.[1]

beforeEach(() => { useDesignStore.setState(makeDesignDefaults()) })

describe('buildGithubPushFiles', () => {
  it('ships the brand, not the system root', () => {
    const key = adopt('retro-vintage', 'dark')
    const s = store()
    const brandCss = buildCSS(captureCodeSnapshot(s, key) as never)
    const r = buildGithubPushFiles({ store: s, publishSlug: 'x' })
    expect(r.lead?.key).toBe(key)
    // variables.css is byte for byte the brand's CSS door
    expect(file(r, 'variables.css')).toBe(brandCss)
    expect(accent9(file(r, 'variables.css'))).not.toBe(s.primaryColor)
    const json = JSON.parse(file(r, 'tokens.json'))
    const brandFont = s.themeFoundations?.[key]?.typography?.fontFamily
    expect(brandFont).toBeTruthy()
    expect(brandFont).not.toBe(s.typography.fontFamily)
    if (brandFont) {
      expect(json.typography.fontFamily).toBe(brandFont)
      expect(r.readme).toContain(`**Body font:** ${brandFont}`)
      const foundations = r.skills.find((f) => f.path.endsWith('references/foundations.md'))!.content
      expect(foundations).toContain(`\`font-family-body\` = \`${brandFont}\``)
    }
    expect(r.readme).toContain(`**Primary color:** \`${accent9(brandCss)}\``)
    expect(r.readme).not.toMatch(/\*\*Themes:\*\*.*Core/)
    expect(r.files.some((f) => f.path.startsWith(BRANDS_DIR))).toBe(false)
  })

  it('keeps the whole editor snapshot in .escala/system.json', () => {
    adopt('core-minimal')
    const r = buildGithubPushFiles({ store: store(), publishSlug: 'slug', publishClaim: 'claim' })
    const sys = JSON.parse(file(r, '.escala/system.json'))
    expect(sys.snapshot.themeOrder).toEqual(store().themeOrder)
    expect(sys.publishSlug).toBe('slug')
  })

  it('writes every brand under brands/ when there are several, and the root is the first', () => {
    const keys = ['core-minimal', 'neo-brutalism', 'retro-vintage'].map((id) => adopt(id))
    const s = store()
    const r = buildGithubPushFiles({ store: s, publishSlug: 'x' })
    expect(r.lead?.key).toBe(keys[0])
    expect(r.brands).toHaveLength(3)
    expect(r.prune).toContain(BRANDS_DIR)
    for (const b of r.brands) {
      expect(file(r, `${BRANDS_DIR}${b.slug}/variables.css`)).toBe(buildCSS(captureCodeSnapshot(s, b.key) as never))
      expect(file(r, `${BRANDS_DIR}${b.slug}/tokens.json`)).toBeTruthy()
      expect(r.readme).toContain(`${BRANDS_DIR}${b.slug}/variables.css`)
    }
    expect(file(r, 'variables.css')).toBe(file(r, `${BRANDS_DIR}${r.brands[0].slug}/variables.css`))
  })

  it('a system with no brand ships the system as it is', () => {
    const r = buildGithubPushFiles({ store: store(), publishSlug: 'x' })
    expect(r.lead).toBeNull()
    expect(file(r, 'variables.css')).toBe(buildCSS(store() as never))
  })
})

describe('shouldWriteReadme', () => {
  it('replaces an Escala README written before the marker, never a person\'s', () => {
    expect(shouldWriteReadme('# Escala — Design System\n\n> Generated by [Escala Tokens](https://www.escalatokens.com)\n\n## Overview\n- a\n- b\n')).toBe(true)
    expect(shouldWriteReadme('# My app\n\nOur design system notes.\n\n## Setup\nnpm i\n')).toBe(false)
    expect(shouldWriteReadme('# My app\n\nSee notes.\n\nThanks to > Generated by [Escala Tokens](https://www.escalatokens.com)\n')).toBe(false)
  })
})

describe('leadBrandJson (the plugin push)', () => {
  it('puts the lead brand\'s foundations at the root of a published payload', async () => {
    const { generateTokenJSON } = await import('../tokenGenerator')
    const { leadBrandJson, buildRepoFiles } = await import('../repoExport')
    const key = adopt('retro-vintage')
    const s = store()
    type Json = { typography: { fontFamily?: string }; radiusRoles?: unknown; icons: { weight?: string }; foundationsByTheme: Record<string, { radiusRoles?: unknown; iconWeight?: string }> }
    const published = generateTokenJSON(s as never) as unknown as Json
    const brandFont = s.themeFoundations?.[key]?.typography?.fontFamily
    expect(published.typography.fontFamily).not.toBe(brandFont) // the root is the system default
    const baked = leadBrandJson(published as never) as unknown as Json
    expect(baked.typography.fontFamily).toBe(brandFont)
    expect(baked.radiusRoles).toEqual(published.foundationsByTheme[key].radiusRoles)
    expect(baked.icons.weight).toBe(published.foundationsByTheme[key].iconWeight)
    expect(published.typography.fontFamily).not.toBe(brandFont) // input untouched
    const build = buildRepoFiles(published as never, { readme: true })
    const foundations = build.files.find((f) => f.path.endsWith('references/foundations.md'))!.content
    expect(foundations).toContain(`\`font-family-body\` = \`${brandFont}\``)
  })
})

describe('a brand made in Dark', () => {
  it('ships both ramps, dark first, and gradients in the brand colour', () => {
    const key = adopt('retro-vintage', 'dark')
    const s = store()
    const r = buildGithubPushFiles({ store: s, publishSlug: 'x' })
    const css = file(r, 'variables.css')
    const snap = captureCodeSnapshot(s, key)
    const dark1 = snap.primaryDarkScale[1]
    const light1 = snap.primaryScale[1]
    // :root carries the dark ramp, `.light` restores the light one
    const rootBlock = css.slice(0, css.indexOf('\n}'))
    expect(rootBlock).toContain(`--color-accent-1: ${dark1};`)
    const lightBlock = css.slice(css.indexOf('.light, [data-theme="light"] {'))
    expect(lightBlock).toContain(`--color-accent-1: ${light1};`)
    // README: both appearances, the brand's first
    expect(r.readme).toContain('| Token | Dark | Light |')
    expect(r.readme).toContain(`| \`--color-accent-1\` | \`${dark1}\` | \`${light1}\` |`)
    expect(r.readme).toContain('### Semantic roles (Categorical)')
    expect(r.readme).toMatch(/\| `--color-action-primary-default` \| `#[0-9a-f]{6,8}` \| `#[0-9a-f]{6,8}` \|/)
    // linked gradients follow the brand, not the system accent
    expect(css).toContain(snap.primaryScale[9])
    const cover = /--gradient-brand-cover:\s*([^;]+);/.exec(css)![1]
    expect(cover).toContain(snap.primaryScale[9])
    expect(cover).not.toContain(s.primaryColor)
  })
})

describe('the whole component catalogue', () => {
  it('documents every component, marks the selection, and links it from the README', async () => {
    const { COMPONENTS } = await import('../componentCatalogue')
    adopt('core-minimal')
    useDesignStore.setState({ selectedComponents: ['Button', 'Input'] })
    const r = buildGithubPushFiles({ store: store(), publishSlug: 'x' })
    const contracts = r.files.filter((f) => f.path.startsWith('contracts/components/'))
    expect(contracts).toHaveLength(COMPONENTS.length)
    const specs = r.skills.filter((f) => f.path.startsWith('.claude/') && f.path.includes('/component-build/components/'))
    expect(specs).toHaveLength(COMPONENTS.length)
    const index = JSON.parse(file(r, 'contracts/components.json'))
    expect(index.components.filter((c: { selected: boolean }) => c.selected).map((c: { key: string }) => c.key).sort()).toEqual(['Button', 'Input'])
    expect(r.prune).toContain('contracts/components/')
    // README: one row per component, every link pointing at a file the push writes
    const rows = r.readme.split('\n').filter((l) => /\| \[Contract\]\(/.test(l))
    expect(rows).toHaveLength(COMPONENTS.length)
    const written = new Set([...r.files, ...r.skills].map((f) => f.path))
    for (const row of rows) {
      for (const [, href] of row.matchAll(/\]\(([^)]+)\)/g)) expect(written.has(href.replace(/%20/g, ' ')), href).toBe(true)
    }
    expect(rows.find((l) => l.startsWith('| Button |'))).toContain('| Yes |')
  })
})
