/** English is normally empty — an unmatched key falls through to the source
 *  string, which IS the English copy. The exception is a DISAMBIGUATED key:
 *  when one English word has two jobs, the source string has to carry the
 *  distinction ("Copy" the verb on a button vs. "Copy" the noun appended to a
 *  duplicated theme's name, which translate differently — Copiar/Copia,
 *  Copier/Copie). The parenthetical makes the key unique, and this entry is
 *  what stops that parenthetical from reaching the screen in English. */
const en: Record<string, string> = {
  'Copy (duplicated theme suffix)': 'Copy',
}

const messages: Record<Locale, Record<string, string>> = { en, es, fr }

/** English is the default for everyone. Another language applies only when the
 *  person picked it (stored by the Language menu) — the browser's own language
 *  is deliberately NOT consulted, so a first visit always lands in English. */
function initialLocale(): Locale {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    if (stored === 'en' || stored === 'es' || stored === 'fr') return stored
  } catch {
    // Storage blocked (private mode, strict settings): fall through to English.
  }
  return 'en'
}

function interpolate(message: string, vars?: Record<string, string | number>): string {
  if (!vars) return message
  return Object.entries(vars).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    message,
  )
}

interface I18nContextValue {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (source: string, vars?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(initialLocale)

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, locale)
    document.documentElement.lang = locale
  }, [locale])

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale,
    t: (source, vars) => interpolate(messages[locale][source] ?? source, vars),
  }), [locale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
