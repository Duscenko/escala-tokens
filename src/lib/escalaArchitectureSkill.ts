/** `[ROLE: Name] text` → `{ name, text }`. */
function splitComment(raw: string | undefined): { name: string; text: string } {
  if (!raw) return { name: '', text: '' }
  const m = /^\[ROLE:\s*([^\]]+)\]\s*(.*)$/s.exec(raw)
  return m ? { name: m[1].trim(), text: m[2].trim() } : { name: '', text: raw }
}

const capitalise = (s: string) => s.charAt(0).toUpperCase() + s.slice(1)

/** Theme columns of a brand payload, labelled the way the brand names them. */
function themeColumns(json: TokenJSON): { key: string; label: string }[] {
  const keys = json.colors.themeOrder?.length ? json.colors.themeOrder : Object.keys(json.colors.themes ?? { light: {} })
  return keys.map((key) => ({ key, label: json.colors.themeLabels?.[key] ?? capitalise(key.split('::').pop() ?? key) }))
}

function colorRoles(json: Source): string {
  const roles = categoricalRoleCatalogue()
  const solved = categoricalSolvedRoles()
  const groups = [...new Set(roles.map((r) => r.group))]
  const themes = json ? themeColumns(json) : []
  const arch = json?.colors.architecture?.tokens
  const out: string[] = [header(json, 'colour roles (Categorical)')]

  out.push(
    `${roles.length} roles in ${groups.length} groups. Every role ships as:`,
    '',
    '- **CSS** `--color-<group>-<key>` with dots turned into dashes (`action.primary.hover` → `--color-action-primary-hover`).',
    '- **Figma** collection `Color Semantics`, variable `<Group>/<key path>` (`Action/primary/hover`), one mode per theme (Light, Dark, a brand…).',
    '- **Recipes / tokens.json** `color.<group>.<key>` and `colors.architecture.tokens.<group>.<key>`.',
    '',
    json
      ? `Values are this system's, per theme (${themes.map((t) => t.label).join(' · ')}). An 8-digit hex is translucent — use it as is. They are a snapshot: code and Figma bind the VARIABLE, never the hex.`
      : '`Light` / `Dark` are the schema refs BEFORE a theme resolves them. A plain `{family.N}` is a pinned step of that family\'s 12-step ramp. Anything else is SOLVED per theme (see the marker legend at the end) — the hex moves with the brand, so never copy a hex from one system into another.',
    '',
  )

  for (const g of groups) {
    const [label, hint] = COLOR_GROUP_META[g] ?? [g, '']
    const rows = roles.filter((r) => r.group === g).map((r) => {
      const id = `${r.group}.${r.key}`
      const { name, text } = splitComment(CATEGORICAL_ROLE_COMMENTS[id])
      const use = name ? `**${name}.** ${text}` : text
      const names = [`\`${id}\``, `\`--color-${id.replace(/\./g, '-')}\``, `\`${figmaSemanticName(id)}\``]
      if (json) {
        const byTheme = arch?.[r.group]?.[r.key]
        return [...names, ...themes.map((t) => (byTheme?.[t.key] ? `\`${byTheme[t.key]}\`` : '—')), use]
      }
      const s = solved[id]
      return [...names, `\`${r.light}\``, `\`${r.dark}\``, s?.light || s?.dark ? 'solved' : 'pinned', use]
    })
    const head = json
      ? ['Role', 'CSS', 'Figma', ...themes.map((t) => t.label), 'Use']
      : ['Role', 'CSS', 'Figma', 'Light', 'Dark', 'Tone', 'Use']
    out.push(`## ${label} — \`${g}.*\``, '', hint, '', table(head, rows), '')
  }

  if (!json) {
    out.push(
      '## Marker legend',
      '',
      table(['Marker', 'Means'], COLOR_MARKERS.map((m) => [m.forms.map((f) => `\`${f}\``).join(' / '), m.means])),
      '',
    )
  }
  return out.join('\n')
}

