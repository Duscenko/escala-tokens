function files(json: Source, repo = false): Record<string, string> {
  const out = {
    'SKILL.md': skillMd(json, repo),
    'references/color-roles.md': colorRoles(json),
    'references/dimension-roles.md': dimensionRoles(json),
    'references/type-roles.md': typeRoles(json),
  }
  // Outside this repo the "generated from src/lib/…" note points nowhere.
  if (!repo) for (const k of Object.keys(out) as (keyof typeof out)[]) out[k] = out[k].replace(GENERATED, '')
  return out
}

/** The repo skill (`.claude/skills/escala-architecture/`), keyed by path inside it. */
export function buildEscalaSkillReferences(): Record<string, string> {
  return files(undefined, true)
}

