/** No json = the repo skill (defaults); a json = one brand's package. */
type Source = TokenJSON | undefined

const VIEWPORTS: GridViewport[] = ['desktop', 'tablet', 'mobile']

const GENERATED = '<!-- GENERATED by `npm run gen:escala-skill` from src/lib/escalaArchitectureSkill.ts. Do not edit by hand. -->\n\n'

const header = (json: Source, title: string) =>
  json ? `# ${projectOf(json)} — ${title}\n` : `${GENERATED}# Escala ${title}\n`

function projectOf(json: TokenJSON): string {
  return json.project?.trim() || 'Design system'
}

function slugOf(project: string): string {
  return project.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'design-system'
}

/** Escape a table cell (pipes and newlines would break the row). */
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ')

function table(head: string[], rows: string[][]): string {
  return [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`),
  ].join('\n')
}

const pxCell = (n: number | null | undefined) => (n === null || n === undefined || !Number.isFinite(n) ? '—' : `${n}px`)

/** `16px / 16px / 12px`, or one value when all three agree. */
function viewportCell(values: (number | null)[]): string {
  const cells = values.map(pxCell)
  return cells.every((c) => c === cells[0]) ? cells[0] : cells.join(' / ')
}

