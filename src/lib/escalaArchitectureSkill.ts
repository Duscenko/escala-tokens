interface FamilyMeta {
  title: string
  css: string
  figma: string | null
  why: string
  /** The family's static scale: the brand's, or the standard. */
  scale: (json: Source) => Record<string, string>
  /** The role → step map a brand ships for the family. */
  roles: (json: TokenJSON) => Record<string, string> | undefined
}

const FAMILY_META: Record<LayoutFamily, FamilyMeta> = {
  radius: { title: 'Radius', css: '--radius-', figma: 'Radius', why: 'Corner roundness. Three INDEPENDENT axes (Boxes · Fields · Selectors) — rounding a checkbox and rounding a modal are different decisions.', scale: (j) => j?.radius ?? RADIUS_STANDARD, roles: (j) => j.radiusRoles },
  spacing: { title: 'Spacing', css: '--spacing-', figma: 'Spacing', why: 'The AIR between and inside things. Tightens on smaller viewports.', scale: (j) => j?.spacing ?? SPACING_STANDARD, roles: (j) => j.spacingRoleRefs ?? j.spacingRoles },
  size: { title: 'Size', css: '--size-', figma: 'Size', why: 'The OBJECT: control heights and hit areas. Holds or grows on touch — never mixed with spacing.', scale: (j) => j?.sizes ?? SIZE_STANDARD, roles: (j) => j.sizeRoles },
  selector: { title: 'Selector', css: '--selector-', figma: 'Selector', why: 'The square a checkbox, radio or switch knob is drawn in. Not a control height.', scale: (j) => j?.selector ?? SELECTOR_STANDARD, roles: (j) => j.selectorRoles },
  stroke: { title: 'Stroke', css: '--stroke-', figma: 'Stroke', why: 'Border widths. The colour of a stroke is a Border colour role, never this.', scale: (j) => j?.stroke ?? STROKE_STANDARD, roles: (j) => j.strokeRoles },
  breakpoint: { title: 'Breakpoint', css: '--breakpoint-', figma: null, why: 'Viewport cuts. The grid (columns · gutter · margin · container) changes at these.', scale: (j) => (j ? extractBreakpoints(j.grid) : BREAKPOINT_STANDARD), roles: (j) => j.breakpointRoles },
}

/** A brand role's px on Desktop · Tablet · Mobile. */
function brandRolePx(json: TokenJSON, family: LayoutFamily, role: string): (number | null)[] {
  const meta = FAMILY_META[family]
  const scale = meta.scale(json)
  if (family === 'radius') {
    if (json.radiusRoles?.[role] === undefined) return [null, null, null]
    return VIEWPORTS.map((vp) => roleValuePx(radiusRoleAt(json.radiusRoles, json.radiusRoleViewports, role, vp), scale))
  }
  const value = meta.roles(json)?.[role]
  if (family === 'spacing' && value) {
    const responsive = json.spacingResponsive?.[value]
    if (responsive) return VIEWPORTS.map((vp) => roleValuePx(responsive[vp] ?? responsive.desktop, scale))
  }
  const one = roleValuePx(value, scale)
  return [one, one, one]
}

/** Default px of a role in the standard system (schema mode). */
function defaultRolePx(family: LayoutFamily, primitive: string): string {
  if (primitive.startsWith('dimension-')) return `${primitive.slice('dimension-'.length)}px`
  const scale = FAMILY_META[family].scale(undefined)
  if (family === 'spacing' && SPACING_RESPONSIVE[primitive]) {
    const r = SPACING_RESPONSIVE[primitive]
    return VIEWPORTS.map((vp) => scale[r[vp]] ?? r[vp]).join(' / ')
  }
  return scale[primitive] ?? '—'
}

/** The mobile breakpoint role is a MAX-width, one below the value it aliases. */
const breakpointCell = (role: string, v: string) => (role === 'mobile' && v !== '—' ? `< ${v}` : v)

function dimensionRoles(json: Source): string {
  const out: string[] = [header(json, 'dimension roles')]
  out.push(
    'Every length is ONE global ladder, `Dimension Primitives` (`--dimension-<px>`, `{dimension.<px>}`; `3_5` = 3.5px, `-8` = −8px). Each family has a static scale (steps) and ROLES that alias a step. **Components read roles.** A step is only for anatomy no role covers.',
    '',
    '- **CSS** `--<family>-<role>` (`--radius-action`, `--spacing-gap-group`, `--size-control`). Roles that step down per viewport are re-declared inside the `@media (max-width: …)` blocks of `variables.css` — read the variable, never hard-code the mobile value.',
    '- **Figma** collection `Dimension Semantics`, variable `<Family>/role/<role>` (`Radius/role/action`), modes = viewports **Desktop · Tablet · Mobile** (never Light/Dark: a length does not change with appearance).',
    '- **Recipes / tokens.json** `<family>.<role>` (`radius.action`, `spacing.inset-surface`) and `<family>Roles` maps.',
    '',
    json
      ? "Values are this system's, as `Desktop / Tablet / Mobile` when they differ. They are a snapshot: bind the role, never its px."
      : "Defaults below are the standard system (4px spacing base, Rounded radius, 40px control). A brand may re-point any role — resolve it from the brand's own files.",
    '',
  )

  const families: LayoutFamily[] = ['radius', 'spacing', 'size', 'selector', 'stroke', 'breakpoint']
  for (const f of families) {
    const meta = FAMILY_META[f]
    out.push(`## ${meta.title}`, '', meta.why, '')
    for (const g of LAYOUT_ROLE_GROUPS[f]) {
      const rows = LAYOUT_ROLES[f].filter((r) => r.group === g.id).map((r) => {
        const names = [`\`${f}.${r.key}\``, `\`${meta.css}${r.key}\``, meta.figma ? `\`${meta.figma}/role/${r.key}\`` : '—']
        if (json) return [...names, breakpointCell(r.key, viewportCell(brandRolePx(json, f, r.key))), r.description]
        return [...names, `\`${r.primitive}\``, breakpointCell(r.key, defaultRolePx(f, r.primitive)), r.description]
      })
      if (!rows.length) continue
      const head = json ? ['Role', 'CSS', 'Figma', 'Value', 'Use'] : ['Role', 'CSS', 'Figma', 'Default step', 'Default px', 'Use']
      out.push(`### ${g.label} — ${g.hint}`, '', table(head, rows), '')
    }
    const scale = Object.entries(meta.scale(json)).sort((x, y) => parseFloat(x[1]) - parseFloat(y[1]))
    out.push(`Static scale: ${scale.map(([k, v]) => `\`${k}\` ${v}`).join(' · ')}`, '')

    if (f === 'radius') {
      out.push(
        '**Axes.** ' + RADIUS_GROUPS.map((g) => `${g.label} (${g.hint}) → ${g.roles.map((r) => `\`radius.${r}\``).join(', ')}`).join('; ') + '. `radius.pill` is not an axis: it means "a circle" and stays `full`.',
        '',
        '**Responsive.** Each step reads one rung smaller on Tablet and Mobile (two from 3xl up):',
        '',
        table(['Step', 'Desktop', 'Tablet', 'Mobile'], Object.entries(RADIUS_RESPONSIVE).map(([k, v]) => [`\`${k}\``, v.desktop, v.tablet, v.mobile])),
        '',
        '**Nesting.** A child flush inside a parent uses r = R − padding (concentric). A button floating inside a card is NOT a nested pair.',
        '',
      )
    }
    if (f === 'spacing') {
      const responsive = json?.spacingResponsive ?? SPACING_RESPONSIVE
      const spacingScale = meta.scale(json)
      out.push(
        `**Inset sides.** ${INSET_ROLES.map((r) => `\`${r}\``).join(', ')} each have \`-top · -right · -bottom · -left\` (\`--spacing-inset-surface-top\`). An unset side FOLLOWS its inset. A fixed-height control uses only left/right — its height is \`size.*\`.`,
        '',
        '**Responsive tokens** (static step per viewport) that roles alias — Component · Section · Layout:',
        '',
        table(['Token', 'Desktop', 'Tablet', 'Mobile'], Object.entries(responsive).map(([k, v]) => [
          `\`spacing.${k}\``,
          ...VIEWPORTS.map((vp) => {
            const st = v[vp] ?? v.desktop
            return `${spacingScale[st] ?? st} (${st})`
          }),
        ])),
        '',
        ...(json ? [] : [
          '**Modes** (one decision setting control base, card padding and border width together): ' +
            SPACING_MODES.map((m) => `${m.label} — ${m.description}`).join(' · '),
          '',
        ]),
      )
    }
    if (f === 'size') {
      const iconRoles = json?.icons?.sizes?.roles
      out.push(
        `**Icons scale with controls.** Roles \`icon.<role>\` → CSS \`--icon-<role>\`, Figma \`Icon/role/<role>\`${json ? '' : ' (reference control md = 40px)'}:`,
        '',
        table(['Role', json ? 'Value' : 'Default px', 'Use'], ICON_ROLES.map((r) => [
          `\`icon.${r}\``,
          json ? pxCell(parseFloat(json.icons?.sizes?.scale?.[iconRoles?.[r] ?? r] ?? iconRoles?.[r] ?? '')) : `${ICON_SIZE_PX[r]}px`,
          ICON_ROLE_DESCRIPTION[r],
        ])),
        '',
        'Below 16px a thin/light icon weight renders regular.',
        '',
      )
    }
    if (f === 'breakpoint') {
      out.push('**Grid per viewport** (`--grid-columns · --grid-gutter · --grid-margin · --grid-container`, Figma `Grid/*` per mode):', '')
      if (json?.gridStyles?.length) {
        out.push(table(
          ['Figma grid style', 'Viewport', 'Width', 'Columns', 'Gutter', 'Margin'],
          json.gridStyles.map((g) => [`\`Grid/${g.label ?? g.key}\``, g.viewport ?? '—', pxCell(g.width), String(g.columns ?? '—'), pxCell(g.gutter), pxCell(g.margin)]),
        ), '')
      } else {
        out.push(table(['Viewport', 'Columns', 'Gutter', 'Margin', 'Container'], Object.entries(GRID_FRAME_STANDARD).map(([vp, a]) => [
          vp,
          a.columns,
          `${SPACING_STANDARD[a.gutter] ?? a.gutter} (spacing ${a.gutter})`,
          `${SPACING_STANDARD[a.margin] ?? a.margin} (spacing ${a.margin})`,
          a.container === 'none' ? 'none' : `${BREAKPOINT_STANDARD[a.container as keyof typeof BREAKPOINT_STANDARD] ?? a.container} (breakpoint ${a.container})`,
        ])), '')
      }
    }
  }
  return out.join('\n')
}

// ── Typography ──────────────────────────────────────────────────────────────

function schemaAliasCell(a: TypeAlias): string {
  return `${a.size} · ${a.weight}${a.family === 'display' ? ' · heading font' : ''}`
}

/** `16px / 24px · 600`, read from the brand's own type primitives. */
function brandAliasCell(json: TokenJSON, a: { family: string; size: string; weight: string } | undefined): string {
  if (!a) return '—'
  const t = json.typography
  const size = t.sizes?.[a.size] ?? a.size
  const lh = t.lineHeights?.[a.size]
  const weight = t.weights?.[a.weight] ?? a.weight
  return `${size}${lh ? ` / ${lh}` : ''} · ${weight}${a.family === 'display' ? ' · heading font' : ''}`
}

function typeRoles(json: Source): string {
  const out: string[] = [header(json, 'type roles')]
  out.push(
    'Two layers. **Primitives**: two families, four weights, one size scale with its line-height and derived tracking. **Roles**: each role aliases a family + size + weight PER VIEWPORT. Components and screens use roles only.',
    '',
    '- **CSS** five facets per role, plus `-tablet` / `-mobile` twins: `--text-<role>-font-family`, `--text-<role>-font-size`, `--text-<role>-font-weight`, `--text-<role>-line-height`, `--text-<role>-letter-spacing` (e.g. `--text-button-font-size`, `--text-heading-lg-font-size-mobile`).',
    '- **Figma** text style `Type/<role>` (`Type/label`); the `Typography` collection carries `role/<role>/size|weight|family|line-height|letter-spacing` with modes Desktop · Tablet · Mobile.',
    '- **Recipes / tokens.json** `type.<role>` and `typography.roles`.',
    '',
  )
  if (json) {
    const t = json.typography
    out.push(`This system: body font **${t.fontFamily}**, heading font **${t.headingFontFamily ?? t.fontFamily}**. Cells read \`size / line-height · weight\`.`, '')
  }
  for (const g of TYPE_ROLE_GROUPS) {
    const rows = TYPE_ROLES.filter((r) => r.group === g.id).map((r) => {
      const names = [`\`type.${r.key}\``, `\`--text-${r.key}-*\``, `\`Type/${r.key}\``]
      if (json) {
        const role = json.typography.roles?.[r.key]
        return [...names, brandAliasCell(json, role?.desktop), brandAliasCell(json, role?.tablet ?? role?.desktop), brandAliasCell(json, role?.mobile), r.description]
      }
      return [...names, schemaAliasCell(r.desktop), schemaAliasCell(r.tablet), schemaAliasCell(r.mobile), r.description]
    })
    out.push(`## ${g.label}`, '', g.hint, '', table(['Role', 'CSS', 'Figma', 'Desktop', 'Tablet', 'Mobile', 'Use'], rows), '')
  }

  const sizes = json?.typography.sizes ?? FONT_SIZE_STANDARD
  const lineHeights = json?.typography.lineHeights ?? LINE_HEIGHT_STANDARD
  const weights = json?.typography.weights ?? Object.fromEntries(FONT_WEIGHT_BASES.map((w) => [w.key, w.weight]))
  out.push(
    '## Primitives',
    '',
    `**Families:** ${FONT_FAMILY_ROWS.map((f) => `\`--${f.key}\` (${f.role === 'display' ? 'heading / display' : 'body, headings by default'})`).join(' · ')}.`,
    '',
    `**Weights:** ${FONT_WEIGHT_BASES.map((w) => `\`--font-weight-${w.key}\` ${weights[w.key] ?? w.weight}`).join(' · ')} (each with an \`-italic\` row in Figma).`,
    '',
    table(
      ['Size step', 'Font size', 'Line height', 'Tracking'],
      TYPE_SCALE_KEYS.map((k) => [`\`${k}\``, sizes[k] ?? '—', lineHeights[k] ?? '—', json?.typography.letterSpacings?.[k] ?? letterSpacingFor(k, sizes[k])]),
    ),
    '',
    'CSS: `--font-size-<step>`, `--line-height-<step>`, `--letter-spacing-<step>`. Tracking is derived from the size, never stored. The Text size dial scales every step and its leading by one factor, so the rhythm survives.',
    '',
  )
  return out.join('\n')
}

