// `checkers/binding-lint.mjs` — the second checker in the agent package
// (design-plans/agent-ready-contracts.md, Phase 4 item 3).
//
// token-lint catches a raw value where a token exists. This one catches the
// subtler mistake: a REAL token on the wrong state — a Button's Hover painted
// with `action.primary.default`. It reads the CSS an agent wrote, finds every
// rule aimed at an Escala component (`[data-escala="<Key>"]`, its variant
// attributes, its state pseudo-classes, `[data-part="<Key>.<slot>"]`),
// resolves what `contracts/<Key>.json` `bindings` say that slot paints in that
// variant and state, and fails when the `var()` differs.
//
// Dependency-free Node, generated (no per-system data: the contracts carry it).

import { CONTRACT_SCHEMA } from '../contractCore'
import type { AgentBundleFile } from './types'

export const BINDING_LINT_PATH = 'checkers/binding-lint.mjs'

export function buildBindingCheckerFile(): AgentBundleFile {
  const text = String.raw`#!/usr/bin/env node
// binding-lint — generated by Escala. Reads ../contracts/<Component>.json (schema ${CONTRACT_SCHEMA}).
// Usage: node checkers/binding-lint.mjs file.css [file.tsx ...]
// Fails (exit 1) when a rule paints an Escala component's slot, in a variant or state, with a
// different CSS variable than the contract's bindings, or targets a component with no contract.

import { readFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const CONTRACTS = join(dirname(fileURLToPath(import.meta.url)), '..', 'contracts')

// Recipe property → the CSS properties the stylesheet writes for it (react/recipes.css).
const PROPS = {
  fill: ['background', 'background-color'],
  text: ['color'],
  stroke: ['border-color'],
}

// A pseudo-class or attribute in the selector → the State value it renders.
const STATES = [
  [/\[data-force-state=["']?([A-Za-z]+)["']?\]/, (m) => m[1]],
  [/:hover\b/, () => 'Hover'],
  [/:active\b/, () => 'Pressed'],
  [/:focus-visible\b|:focus\b/, () => 'Focused'],
  [/\[aria-disabled=["']?true["']?\]|:disabled\b|\[data-disabled\]/, () => 'Disabled'],
  [/\[aria-invalid=["']?true["']?\]/, () => 'Error'],
]

const cache = new Map()
function contractOf(key) {
  if (!cache.has(key)) {
    const file = join(CONTRACTS, key + '.json')
    cache.set(key, existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : null)
  }
  return cache.get(key)
}

/** Split on a separator outside brackets and parentheses. */
function splitTop(s, sep) {
  const out = []
  let depth = 0
  let cur = ''
  for (const ch of s) {
    if (ch === '(' || ch === '[') depth++
    if (ch === ')' || ch === ']') depth--
    if (depth === 0 && sep.test(ch)) { if (cur.trim()) out.push(cur.trim()); cur = '' } else cur += ch
  }
  if (cur.trim()) out.push(cur.trim())
  return out
}

/** :not(...) says what the element is NOT: never read a variant or a state from it. */
function stripNot(compound) {
  let out = compound
  for (let i = out.indexOf(':not('); i >= 0; i = out.indexOf(':not(')) {
    let depth = 0
    let j = i + 4
    for (; j < out.length; j++) { if (out[j] === '(') depth++; if (out[j] === ')' && --depth === 0) break }
    out = out.slice(0, i) + out.slice(j + 1)
  }
  return out
}

function canonical(list, raw) {
  return list.find((v) => v.toLowerCase() === String(raw).toLowerCase())
}

/** The render a selector describes: { contract, values, slot } or an error string, or null (not Escala). */
function target(selector) {
  const compounds = splitTop(selector, /[\s>+~]/)
  const rootAt = compounds.findIndex((c) => /\[data-escala=["']?[A-Za-z]/.test(c))
  if (rootAt < 0) return null
  const root = stripNot(compounds[rootAt])
  const key = /\[data-escala=["']?([A-Za-z][A-Za-z0-9]*)/.exec(root)[1]
  const contract = contractOf(key)
  if (!contract) return { error: 'no contract for "' + key + '" — not an Escala component (contracts/index.json lists them)' }
  const values = { ...contract.api.defaults }
  for (const axis of contract.api.axes) {
    if (axis.name === 'State') continue
    const m = new RegExp('\\[data-' + axis.name.toLowerCase() + '=["\']?([^"\'\\]]+)').exec(root)
    if (m) values[axis.name] = canonical(axis.values, m[1]) ?? m[1]
  }
  const stateAxis = contract.api.axes.find((a) => a.name === 'State')
  if (stateAxis) {
    for (const [re, pick] of STATES) {
      const m = re.exec(root)
      if (!m) continue
      const v = canonical(stateAxis.values, pick(m))
      if (v) { values.State = v; break }
    }
  }
  const last = compounds[compounds.length - 1]
  let slot = null
  if (rootAt === compounds.length - 1) slot = contract.anatomy.slots[0] ?? 'root'
  else {
    const part = new RegExp('\\[data-part=["\']?' + key + '\\.([A-Za-z-]+)').exec(last)
    if (part) slot = part[1]
  }
  return slot ? { contract, values, slot } : null
}

/** Merge every binding part whose combination matches, in order (the contract's rule). */
function resolve(contract, values) {
  const out = {}
  for (const part of contract.bindings) {
    const slots = part.values[part.axes.map((a) => values[a] ?? '').join('|')]
    if (!slots) continue
    for (const [slot, props] of Object.entries(slots)) out[slot] = { ...(out[slot] ?? {}), ...props }
  }
  return out
}

function expectedCss(contract, ref) {
  if (ref === 'none') return 'transparent'
  const n = contract.names[ref]
  return n ? n.css : null
}

function lint(source, label) {
  let issues = 0
  const css = source.replace(/\/\*[\s\S]*?\*\//g, '')
  const rule = /([^{}]+)\{([^{}]*)\}/g
  let m
  while ((m = rule.exec(css))) {
    const decls = m[2].split(';').map((d) => d.trim()).filter(Boolean).map((d) => {
      const i = d.indexOf(':')
      return [d.slice(0, i).trim().toLowerCase(), d.slice(i + 1).trim()]
    })
    for (const selector of splitTop(m[1].trim(), /,/)) {
      const t = target(selector)
      if (!t) continue
      if (t.error) { console.log(label + '  ' + selector + '  ' + t.error); issues++; continue }
      const slots = resolve(t.contract, t.values)[t.slot] ?? {}
      const where = t.contract.key + ' ' + t.slot + ' at ' + Object.entries(t.values).map(([a, v]) => a + '=' + v).join(', ')
      for (const [prop, cssProps] of Object.entries(PROPS)) {
        const ref = slots[prop]
        if (!ref) continue
        const want = expectedCss(t.contract, ref)
        if (!want) continue
        for (const [name, value] of decls) {
          if (!cssProps.includes(name)) continue
          const used = /var\(\s*(--[A-Za-z0-9-]+)/.exec(value)?.[1] ?? (/^(transparent|none)$/.test(value) ? 'transparent' : null)
          if (!used || used === want) continue
          console.log(label + '  ' + selector + '  ' + name + ': ' + value + '  ✗  ' + where + ' binds ' + ref + ' → var(' + want + ')')
          issues++
        }
      }
    }
  }
  return issues
}

const files = process.argv.slice(2)
if (!files.length) {
  console.error('usage: node checkers/binding-lint.mjs file.css [file ...]')
  process.exit(2)
}
let total = 0
for (const f of files) total += lint(readFileSync(f, 'utf8'), f)
if (total) {
  console.log('\n' + total + ' binding issue(s). Paint each state with the role its contract binds (contracts/<Component>.json → bindings).')
  process.exit(1)
}
console.log('binding-lint: every Escala rule paints the role its contract binds.')
`
  return { path: BINDING_LINT_PATH, text }
}
