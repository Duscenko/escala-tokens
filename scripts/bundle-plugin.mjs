// Bundles the sibling Figma plugin (manifest + build output) into a downloadable
// zip served from /public, so the "Bring to Figma" view can hand it to designers.
//
// The plugin lives in a SEPARATE repo (../escala-figma-plugin) that is
// NOT present on Vercel's build, so the resulting zip is committed as a static
// asset. Re-run this and commit the zip whenever the plugin changes:
//
//   npm run bundle:plugin
//
import { execFileSync } from 'node:child_process'
import { existsSync, rmSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(__dirname, '..')
const pluginDir = path.resolve(repoRoot, '..', 'escala-figma-plugin')
const publicDir = path.resolve(repoRoot, 'public')
const out = path.join(publicDir, 'escala-figma-plugin.zip')

const manifest = path.join(pluginDir, 'manifest.json')
const dist = path.join(pluginDir, 'dist')

if (!existsSync(manifest) || !existsSync(dist)) {
  console.warn(
    `[bundle-plugin] Skipped — plugin sources not found at ${pluginDir}.\n` +
      '  This is expected on CI/Vercel; the committed public/ zip is used instead.',
  )
  process.exit(0)
}

mkdirSync(publicDir, { recursive: true })
rmSync(out, { force: true })

// `zip` ships with macOS/Linux. -r recurse dist/, -X strip extra attrs, exclude cruft.
execFileSync('zip', ['-r', '-X', out, 'manifest.json', 'dist', '-x', '*.DS_Store'], {
  cwd: pluginDir,
  stdio: 'inherit',
})

console.log(`[bundle-plugin] Wrote ${path.relative(repoRoot, out)}`)

// ── Regenerate src/lib/pluginVersion.ts ──
// A content hash of the plugin's SHIPPED files (not the zip — a re-zip embeds
// fresh mtimes, so its bytes aren't stable for unchanged content). This is what
// the app compares against the user's last-downloaded build to show an
// "Update available" hint on the Sync hub's "Download plugin" row.
const hashFiles = ['manifest.json', 'dist/code.js', 'dist/ui.html']
const h = createHash('sha256')
for (const rel of hashFiles) {
  h.update(rel)
  h.update('\0')
  h.update(readFileSync(path.join(pluginDir, rel)))
}
const build = h.digest('hex').slice(0, 12)

let version = '0.0.0'
try {
  version = JSON.parse(readFileSync(path.join(pluginDir, 'package.json'), 'utf8')).version ?? version
} catch {
  // package.json is optional — fall back to 0.0.0 for the display string.
}

const versionFile = path.join(repoRoot, 'src', 'lib', 'pluginVersion.ts')
writeFileSync(
  versionFile,
  `// GENERATED by \`npm run bundle:plugin\` — do NOT hand-edit.
//
// \`PLUGIN_BUILD\` is a content hash of the sibling Figma plugin's shipped files
// (manifest + build output), recomputed every time the downloadable zip is
// re-bundled. It's the honest "did the plugin actually change" signal — it
// flips on any real change, without relying on someone bumping the semver.
//
// \`PLUGIN_VERSION\` is the human-readable version from the plugin's package.json,
// shown in the UI. The app compares the user's last-downloaded \`PLUGIN_BUILD\`
// (\`pluginBuildSeen\` in the store) against this to surface an "Update available"
// hint on the Sync hub's "Download plugin" row.
export const PLUGIN_VERSION = '${version}'
export const PLUGIN_BUILD = '${build}'
`,
)
console.log(`[bundle-plugin] Wrote src/lib/pluginVersion.ts (v${version}, build ${build})`)
