/**
 * Writes src/lib/chartRamps.generated.ts — the seven Chart hue ramps of the Figma file
 * (`Color Primitives` › `Charts/EscalaDS/<Hue>` and `<Hue> Dark`, 12 steps each, hidden from
 * publishing) from spec/figma-chart-primitives.json (a read-only dump of that file).
 * Series 1 is not here: it reuses the accent ramp. Never edit the output by hand.
 *
 *   npm run gen:chart-ramps
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const snap = JSON.parse(readFileSync(join(root, 'spec/figma-chart-primitives.json'), 'utf8')) as { groups: Record<string, string> }
const HUES = ['Teal', 'Amber', 'Blue', 'Rose', 'Lime', 'Magenta', 'Orange'] as const

function ramp(group: string): Record<number, string> {
  const raw = snap.groups[group]
  if (!raw) throw new Error(`chart ramps: group "${group}" missing`)
  const out: Record<number, string> = {}
  for (const kv of raw.trim().split(/\s+/)) {
    const [k, v] = kv.split('=')
    out[Number(k)] = `#${v.toLowerCase()}`
  }
  if (Object.keys(out).length !== 12) throw new Error(`chart ramps: "${group}" is not 12 steps`)
  return out
}

const data = Object.fromEntries(HUES.map((h) => [h.toLowerCase(), {
  light: ramp(`Charts/EscalaDS/${h}`),
  dark: ramp(`Charts/EscalaDS/${h} Dark`),
}]))

writeFileSync(join(root, 'src/lib/chartRamps.generated.ts'), [
  '// GENERATED by scripts/gen-chart-ramps.ts from spec/figma-chart-primitives.json.',
  '// Do not edit: re-dump the Figma file into the snapshot, then `npm run gen:chart-ramps`.',
  '// The Chart hue ramps of the Figma library (`Charts/EscalaDS/<Hue>[ Dark]`). Series 1 reuses the accent.',
  '',
  `export const CHART_RAMPS = ${JSON.stringify(data, null, 2)} as const`,
  '',
  "export type ChartHue = keyof typeof CHART_RAMPS",
  '',
].join('\n'))
console.log('wrote src/lib/chartRamps.generated.ts')
