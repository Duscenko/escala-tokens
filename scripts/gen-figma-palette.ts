/**
 * Writes src/lib/figmaFilePalette.generated.ts — the colour primitives of the
 * Figma file `Escala Design System (Real)` (7j5zukN5HpihGVJMmyjA20), read from
 * the plugin's inventory of that file (escala-figma-plugin/spec/figma-variables.txt).
 *
 * Owner's call (2026-11-12): the file's palette is curated and tested, and it
 * wins over the generator. No generator rule reproduces it (99 of 120 solid
 * steps and most alpha steps differ for the same accent), so the system the
 * file shows ships it as DATA. Never edit the output by hand: re-dump the file
 * into the inventory, then run `npm run gen:figma-palette`.
 *
 *   npm run gen:figma-palette
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const INVENTORY = join(root, '../escala-figma-plugin/spec/figma-variables.txt')
const OUT = join(root, 'src/lib/figmaFilePalette.generated.ts')

/** Parses `@ <group> (12): 01=fefdff 02=…` lines under `## Color Primitives`. */
export function parsePrimitiveGroups(text: string): Map<string, Record<number, string>> {
  const groups = new Map<string, Record<number, string>>()
  let inPrimitives = false
  for (const line of text.split('\n')) {
    if (line.startsWith('## ')) { inPrimitives = line.startsWith('## Color Primitives'); continue }
    if (!inPrimitives) continue
    const m = /^@ (.+?) \(\d+\): (.*)$/.exec(line)
    if (!m) continue
    const steps: Record<number, string> = {}
    for (const kv of m[2].trim().split(/\s+/)) {
      const [k, v] = kv.split('=')
      steps[Number(k)] = `#${v.toLowerCase()}`
    }
    groups.set(m[1], steps)
  }
  return groups
}

/** Escala slot → the file's group names (`<NS>` = the system name, EscalaDS). */
const SLOT_GROUPS = {
  accent: 'Accents/<NS>',
  gray: 'Neutrals/<NS> Gray',
  error: 'States/<NS>/Error',
  warning: 'States/<NS>/Warning',
  success: 'States/<NS>/Success',
  info: 'States/<NS>/Info',
} as const

export function buildPaletteModule(text: string, ns = 'EscalaDS'): string {
  const groups = parsePrimitiveGroups(text)
  const need = (name: string) => {
    const g = groups.get(name)
    if (!g || Object.keys(g).length !== 12) throw new Error(`figma palette: group "${name}" missing or not 12 steps`)
    return g
  }
  const families: Record<string, { light: Record<number, string>; dark: Record<number, string>; alpha: Record<number, string>; darkAlpha: Record<number, string> }> = {}
  for (const [slot, pattern] of Object.entries(SLOT_GROUPS)) {
    const base = pattern.replace('<NS>', ns)
    families[slot] = {
      light: need(base),
      dark: need(`${base} Dark`),
      alpha: need(`${base}/Alpha`),
      darkAlpha: need(`${base} Dark/Alpha`),
    }
  }
  const data = {
    accent: families.accent.light[9],
    families,
    blackAlpha: need('Neutrals/Black Alpha'),
    whiteAlpha: need('Neutrals/White Alpha'),
  }
  return [
    '// GENERATED by scripts/gen-figma-palette.ts from escala-figma-plugin/spec/figma-variables.txt.',
    '// Do not edit: re-dump the Figma file into the inventory, then `npm run gen:figma-palette`.',
    '// The colour primitives of the Figma file `Escala Design System (Real)` — curated, and',
    '// the ground truth for the system that file shows (owner, 2026-11-12).',
    '',
    `export const FIGMA_FILE_PALETTE = ${JSON.stringify(data, null, 2)} as const`,
    '',
    'export type FigmaPaletteSlot = keyof typeof FIGMA_FILE_PALETTE.families',
    '',
  ].join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, buildPaletteModule(readFileSync(INVENTORY, 'utf8')))
  console.log(`[gen-figma-palette] Wrote ${OUT.replace(`${root}/`, '')}`)
}
