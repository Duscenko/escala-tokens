// Bundles src/lib/pluginStudio.ts into api/_pluginStudio.mjs.
//
// Vercel runs api/*.ts as plain Node ESM, which needs explicit `.js`
// extensions on relative imports. The generator graph (store, colour layer,
// token generator) is written for Vite and imports extension-less, so the
// function crashed on load when it imported pluginStudio directly. One esbuild
// pass resolves the graph into a single file; npm packages stay external and
// resolve from node_modules. Run by `prebuild`; the output is committed so a
// function build never depends on the order Vercel runs things in.
import { build } from 'esbuild'

await build({
  entryPoints: ['src/lib/pluginStudio.ts'],
  outfile: 'api/_pluginStudio.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  packages: 'external',
  logLevel: 'error',
  banner: { js: '// GENERATED by scripts/build-plugin-studio.mjs — do not edit.' },
})
console.log('[build-plugin-studio] Wrote api/_pluginStudio.mjs')
