/**
 * Reads `components/escala-ui/` from disk and runs the registry transform.
 * Node-only (fs): used by `gen-registry-sources.ts` and the sync test,
 * never by the app or the API (they read the committed generated module).
 */
import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { anatomyIconPx } from '../src/lib/iconSizing'
import { transformEscalaUi, type RegistrySource } from '../src/lib/registry/escalaUiTransform'

export const GENERATED_PATH = 'src/lib/registry/escalaUiSources.generated.ts'

export function readEscalaUiSources(root: string): RegistrySource[] {
  const dir = join(root, 'src/components/escala-ui')
  const iconsSource = readFileSync(join(root, 'src/components/ui/icons.tsx'), 'utf8')
  return readdirSync(dir)
    .filter((f) => /\.(tsx|ts)$/.test(f))
    .sort()
    .map((f) => transformEscalaUi(f, readFileSync(join(dir, f), 'utf8'), { iconsSource, iconOf: anatomyIconPx }))
}

export function renderGeneratedModule(sources: RegistrySource[]): string {
  return [
    '// GENERATED by `npm run gen:registry-sources` from src/components/escala-ui/.',
    '// Do not edit: `shadcnRegistry.test.ts` fails when this drifts from the components.',
    "import type { RegistrySource } from './escalaUiTransform.js'",
    '',
    `export const ESCALA_UI_SOURCES: RegistrySource[] = ${JSON.stringify(sources, null, 2)}`,
    '',
  ].join('\n')
}
